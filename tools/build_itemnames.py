#!/usr/bin/env python3
"""Generate Data/ItemNames.lua: English name + quality for every itemID referenced by Data/Vendors.lua and
Data/Recipes.lua, so those items always have a name in the UI even before the server sends item info.

Source: Blizzard Classic Era client table ItemSparse (columns ID, Display_lang, OverallQualityID) via
https://wago.tools/db2/ItemSparse/csv?branch=wow_classic_era (same export used by build_data.py / build_vendors.py).

Usage: python3 build_itemnames.py <ItemSparse.csv> <addon_dir>
"""
import csv, sys, os, re, datetime

sparse, addon = sys.argv[1], sys.argv[2]
ids = set()
vend = open(os.path.join(addon, 'Data', 'Vendors.lua'), encoding='utf-8').read()
db = vend[vend.index('ns.VendorDB = {'):]
ids.update(int(m) for m in re.findall(r'^\[(\d+)\]=\{', db, re.M))
rec = open(os.path.join(addon, 'Data', 'Recipes.lua'), encoding='utf-8').read()
for m in re.finditer(r'^\[\d+\]=\{"[^"]*",(\d+),[^{]*?,(nil|\d+),\{([\d,]*)\}', rec, re.M):
    ids.add(int(m.group(1)))
    if m.group(2) != 'nil':
        ids.add(int(m.group(2)))
    nums = [int(x) for x in m.group(3).split(',') if x]
    ids.update(nums[0::2])

names = {}
for r in csv.DictReader(open(sparse, newline='', encoding='utf-8')):
    i = int(r['ID'])
    if i in ids and r['Display_lang']:
        names[i] = (r['Display_lang'], int(r['OverallQualityID'] or 1))

def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

stamp = datetime.date.today().isoformat()
L = ['-- AUTO-GENERATED by tools/build_itemnames.py on %s. Do not edit by hand.' % stamp,
     '-- English item names and qualities from Blizzard Classic Era ItemSparse (Display_lang, OverallQualityID) via wago.tools,',
     '-- for every item referenced by Data/Vendors.lua and Data/Recipes.lua. Used only until the client returns live item info.',
     '-- ItemNames[itemID] = { name, quality }',
     'local _, ns = ...',
     'ns.ItemNamesInfo = { generated = "%s", items = %d }' % (stamp, len(names)),
     'ns.ItemNames = {']
for i in sorted(names):
    L.append('[%d]={%s,%d},' % (i, q(names[i][0]), names[i][1]))
L.append('}')
open(os.path.join(addon, 'Data', 'ItemNames.lua'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('items referenced %d, named %d, missing %d' % (len(ids), len(names), len(ids - set(names))))
