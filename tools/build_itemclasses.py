#!/usr/bin/env python3
"""Build Data/ItemClasses.lua: classID / subClassID / inventoryType for every item in the WoW Forever client's
Item table (31,824 items in build 1.60.1.70245, including Forever's own items; all of Data/ItemNames.lua but one).

Source: the WoW Forever client's own Item table (wago.tools, product wowf, build 1.60.1.70245):
  https://wago.tools/db2/Item/csv?build=1.60.1.70245
Usage: python3 tools/build_itemclasses.py Item.csv [Data/ItemNames.lua] [Data/ItemClasses.lua]
Output: ns.ItemClassGroups = { {classID, subClassID, inventoryType, "id,+delta,+delta,..."}, ... }
"""
import csv, re, sys, datetime

src = sys.argv[1]
names = sys.argv[2] if len(sys.argv) > 2 else "Data/ItemNames.lua"
out = sys.argv[3] if len(sys.argv) > 3 else "Data/ItemClasses.lua"
want = set(int(m) for m in re.findall(r"^\[(\d+)\]=", open(names, encoding="utf-8").read(), re.M))
groups, found = {}, 0
with open(src, newline="", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        i = int(r["ID"])
        found += i in want
        if True:
            groups.setdefault((int(r["ClassID"]), int(r["SubclassID"]), int(r["InventoryType"])), []).append(i)
lines = [
    "-- AUTO-GENERATED by tools/build_itemclasses.py on %s. Do not edit by hand." % datetime.date.today().isoformat(),
    "-- classID / subClassID / inventoryType from the WoW Forever client's Item table (wago.tools, wowf 1.60.1.70245)",
    "-- for every item in that table (%d items; %d of the %d in Data/ItemNames.lua). Used for the Market category tree" % (sum(len(v) for v in groups.values()), found, len(want)),
    "-- until the client answers C_Item.GetItemInfoInstant.",
    "-- Each group: { classID, subClassID, inventoryType, \"first,+d,+d,...\" }",
    "local _, ns = ...",
    "ns.ItemClassGroups = {",
]
for key in sorted(groups):
    ids = sorted(groups[key])
    parts, prev = [], 0
    for i in ids:
        parts.append(str(i - prev)); prev = i
    lines.append('{%d,%d,%d,"%s"},' % (key[0], key[1], key[2], ",".join(parts)))
lines.append("}")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("items %d (ItemNames %d/%d), groups %d -> %s" % (sum(len(v) for v in groups.values()), found, len(want), len(groups), out))
