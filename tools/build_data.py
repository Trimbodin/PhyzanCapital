#!/usr/bin/env python3
"""Generate Data/Recipes.lua (vendor data: see build_vendors.py) for Phyzan Capital from Blizzard's
Classic Era client DB2 tables (CSV exports from https://wago.tools/db2/<Table>/csv?branch=wow_classic_era).
Tables used: SkillLineAbility, SpellEffect, SpellReagents, SpellName, ItemSparse, ItemEffect.
Season of Discovery content is excluded by ID range (vanilla spell IDs < 31000, item IDs < 24300).
Usage: python3 build_data.py <csv_dir> <addon_dir>"""
import csv, sys, os, collections
src, out = sys.argv[1], sys.argv[2]
def rows(t): return csv.DictReader(open(os.path.join(src, t + '.csv'), newline='', encoding='utf-8'))
PROF = {171:'Alchemy',164:'Blacksmithing',333:'Enchanting',202:'Engineering',165:'Leatherworking',
        197:'Tailoring',185:'Cooking',129:'First Aid',186:'Mining'}
MAX_SPELL, MAX_ITEM = 31000, 24300
items = {}
for r in rows('ItemSparse'):
    i = int(r['ID'])
    if i < MAX_ITEM:
        items[i] = r
abil = {}
for r in rows('SkillLineAbility'):
    sl, sp = int(r['SkillLine']), int(r['Spell'])
    if sl in PROF and sp < MAX_SPELL:
        abil[sp] = (sl, int(r['TrivialSkillLineRankLow']), int(r['TrivialSkillLineRankHigh']), int(r['AcquireMethod']))
create = {}
teaches = {}  # teaching spell (used by recipe item) -> learned spell, via SPELL_EFFECT_LEARN_SPELL (36)
for r in rows('SpellEffect'):
    sp = int(r['SpellID'])
    if r['Effect'] == '36' and int(r['EffectTriggerSpell'] or 0) > 0:
        teaches[sp] = int(r['EffectTriggerSpell'])
    if sp in abil and r['Effect'] == '24' and int(r['DifficultyID'] or 0) == 0:
        it = int(r['EffectItemType'])
        bp, ds = int(float(r['EffectBasePoints'])), int(r['EffectDieSides'])
        create[sp] = (it, bp + min(ds, 1) if ds else bp, bp + ds)
reag = {}
for r in rows('SpellReagents'):
    sp = int(r['SpellID'])
    if sp in create:
        lst = []
        for k in range(8):
            it, c = int(r['Reagent_%d' % k]), int(r['ReagentCount_%d' % k])
            if it > 0 and c > 0: lst.append((it, c))
        reag[sp] = lst
names = {int(r['ID']): r['Name_lang'] for r in rows('SpellName') if int(r['ID']) in create}
# Recipe items: learned spell -> required skill rank on the recipe item
learned = collections.defaultdict(list)
for r in rows('ItemEffect'):
    learned[int(r['ParentItemID'])].append(int(r['SpellID']))
reqskill = {}
for iid, r in items.items():
    if int(r['RequiredSkill'] or 0) in PROF and int(r['RequiredSkillRank'] or 0) > 0:
        for sp0 in learned.get(iid, []):
            sp = teaches.get(sp0, sp0)
            if sp in create:
                reqskill[sp] = (int(r['RequiredSkillRank']), iid)
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
n = 0
lines = ['-- AUTO-GENERATED by tools/build_data.py from Blizzard Classic Era DB2 tables (wago.tools CSV export).',
         '-- Do not edit by hand. Fields: [spellID] = {prof, productItemID, minMade, maxMade, yellowSkill, grayTrivialSkill,',
         '--   reqSkill (from recipe item, or nil if trainer/unknown), recipeItemID or nil, {reagentItemID, count, ...}, name}',
         'local _, ns = ...', 'ns.RecipeData = {']
for sp in sorted(create):
    if sp not in reag or not reag[sp]: continue
    it, mn, mx = create[sp]
    if it >= MAX_ITEM or it not in items or any(r[0] >= MAX_ITEM for r in reag[sp]): continue
    sl, low, high, _ = abil[sp]
    rs = reqskill.get(sp)
    flat = ','.join('%d,%d' % x for x in reag[sp])
    lines.append('[%d]={%s,%d,%d,%d,%d,%d,%s,%s,{%s},%s},' % (sp, q(PROF[sl]), it, mn, mx, low, high,
                 rs and rs[0] or 'nil', rs and rs[1] or 'nil', flat, q(names.get(sp, '?'))))
    n += 1
lines.append('}')
os.makedirs(os.path.join(out, 'Data'), exist_ok=True)
open(os.path.join(out, 'Data', 'Recipes.lua'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('recipes', n, 'with reqSkill', sum(1 for s in reqskill if s in create))
